from .i18n_extra import EXTRA as _EXTRA  # noqa: E402

for _code, _texts in _EXTRA.items():
    TEXT[_code].update(_texts)

_lang = "de"


def set_lang(lang: str) -> None:
    global _lang
    _lang = lang if lang in TEXT else "de"
    try:                                   # eingebaute Dialoge/Seiten von Hypr Studio in derselben Sprache
        from hyprstudio import i18n as hs_i18n
        hs_i18n.set_lang(_lang)
    except ImportError:
        pass


def lang() -> str:
    return _lang


def t(key: str, **kw) -> str:
    s = TEXT[_lang].get(key) or TEXT["de"].get(key) or key
    return s.format(**kw) if kw else s
